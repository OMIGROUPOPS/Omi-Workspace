equal(summary.terminal_legs, 60);
equal(summary.terminal_rows.length, 60);
equal(summary.source.commit, "41c1f7244af3afa4dade63bc9824808090ada41d");
equal(summary.divergence_rows.length, summary.binding_divergence_receipts);
equal(summary.verified_bound_terminal_legs + (60 - summary.verified_bound_terminal_legs), 60);
const role = json("BENCHMARKED_ROLE_INSTRUMENT_SUMMARY.json");
equal(role.terminal_roles.length, 60);
equal(role.coverage.terminal_legs, 60);
check(role.coverage.called_all_legs_share >= 0 && role.coverage.called_all_legs_share <= 1);
check(role.accuracy.accuracy === null || (role.accuracy.accuracy >= 0 && role.accuracy.accuracy <= 1));
equal(role.rule_binding.ripeness.commit, "41c1f7244af3afa4dade63bc9824808090ada41d");
const flow = json("FLOW_ASSERTIONS.json");
equal(flow.REFLEX_POST_zero.observed, 0);
