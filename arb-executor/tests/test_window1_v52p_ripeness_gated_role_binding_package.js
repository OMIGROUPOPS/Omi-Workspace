equal(deterministic.clean_builds, 2);
equal(deterministic.byte_identical, true);
equal(deterministic.mismatches.length, 0);

process.stdout.write(`${JSON.stringify({ assertions, failures: 0, omissions: 0, deselections: 0 })}\n`);
