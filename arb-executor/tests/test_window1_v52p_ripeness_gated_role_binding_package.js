equal(flow.candidate_role_matches_literal_drift_arithmetic.violations.length, 0);
equal(flow.effective_gate_is_exact_max_and_binding_uses_verified_f.violations.length, 0);
equal(flow.below_gate_abstains_to_V52l.violations.length, 0);
equal(flow.ROLE_UP_STILL_and_below_gate_preserve_V52l_level.violations.length, 0);
